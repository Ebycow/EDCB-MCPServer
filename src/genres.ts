/**
 * ジャンルの表示名（"大分類 - 小分類"）。Material WebUIのcomponent_type_nameと同じ表記にする。
 * 拡張ジャンル（大分類0xE）は放送局独自の付属情報なのでnullを返す
 */
export function genreName(nibble1: number, nibble2: number): string | null {
  if (nibble1 === 0xe) return null;
  const major = ARIB_GENRES[nibble1];
  if (!major) return 'その他';
  const minor = nibble2 === 0xf ? 'その他' : major.minor[nibble2];
  return minor ? `${major.major} - ${minor}` : major.major;
}
